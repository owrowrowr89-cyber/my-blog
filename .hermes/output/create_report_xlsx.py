def set_cell(ws, row, col, value, font=None, fill=None, alignment=None, border=None, number_format=None):
    cell = ws.cell(row=row, column=col, value=value)
    if font: cell.font = font
    if fill: cell.fill = fill
    if alignment: cell.alignment = alignment
    if border: cell.border = border
    if number_format: cell.number_format = number_format
    return cell


def auto_width(ws, min_width=8, max_width=22):
    for col_cells in ws.columns:
        max_len = 0
        col_letter = get_column_letter(col_cells[0].column)
        for cell in col_cells:
            try:
                val = str(cell.value or "")
                max_len = max(max_len, len(val.encode('utf-8')))
            except:
                max_len = max(max_len, len(str(cell.value or "")))
        adjusted = min(max(max_len * 0.9 + 2, min_width), max_width)
        ws.column_dimensions[col_letter].width = adjusted


